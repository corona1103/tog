function splitAnswer(line) {
  const text = stripMarkup(line).replace(/[。！？；]$/, '');
  const parts = text.split(/([，；])/).filter(Boolean);
  const result = [];
  for (let i = 0; i < parts.length; i += 2) {
    const phrase = parts[i];
    if (!phrase) continue;
    result.push(`##${phrase}##${parts[i + 1] || ''}`);
  }
  return result.join('') || `##${text}##`;
}

function sourceLines(poem) {
  return stripMarkup(poem.content)
    .split('##')
    .flatMap(paragraph => paragraph.split('\\n'))
    .map(line => line.trim())
    .filter(Boolean);
}

function fallbackQuestions(poem) {
  const lines = sourceLines(poem);
  const prompts = poem.genre === 1
    ? [
        `《${poem.title}》中，描写相关景物的诗句是：`,
        `《${poem.title}》中，写诗人眼前所见的句子是：`,
        `《${poem.title}》中，表现诗人情感的诗句是：`,
        `《${poem.title}》中，最能体现作品意境的句子是：`,
        `《${poem.title}》中，运用写景手法的诗句是：`,
        `请写出《${poem.title}》中相关的名句：`,
        `《${poem.title}》中，写到这一情景的句子是：`,
        `《${poem.title}》中，表现作者心境的句子是：`,
        `《${poem.title}》中，描绘画面、营造意境的句子是：`,
        `默写《${poem.title}》中的相关诗句：`
      ]
    : [
        `《${poem.title}》中，写到相关情节的句子是：`,
        `《${poem.title}》中，表现人物心情的句子是：`,
        `《${poem.title}》中，描写相关场景的句子是：`,
        `《${poem.title}》中，体现文章主旨的句子是：`,
        `《${poem.title}》中，作者用来表现这一内容的句子是：`,
        `请写出《${poem.title}》中相关的名句：`,
        `《${poem.title}》中，写到这一情形的句子是：`,
        `《${poem.title}》中，表现人物或事物特点的句子是：`,
        `《${poem.title}》中，描写这一画面的句子是：`,
        `默写《${poem.title}》中的相关句子：`
      ];
  const answers = lines.length ? lines : [poem.content];
  return Array.from({ length: 10 }, (_, index) => {
    const answer = answers[index % answers.length];
    return `${prompts[index]}${splitAnswer(answer)}。`;
  });
}

module.exports = ({ poems }) => poems.flatMap(poem => {
  const stems = manualQuestions[poem.title] || fallbackQuestions(poem);
  return stems.slice(0, 10).map((stem, index) => ({ poemId: poem.id, sort: index + 1, stem }));
});
